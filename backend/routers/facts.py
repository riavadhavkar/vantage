"""/api/facts: computed context for a scene, from Wolfram|Alpha. Owner: A.
POST {"text": narrative_text} -> {"facts": [{"label", "query", "answer"}], "provider": "Wolfram|Alpha"}
An LLM picks up to two things in the narration that Wolfram can compute exactly (old money in
today's dollars, distances between named places, the moon phase on a dated night, ages, speeds),
then Wolfram computes them. Nothing here is generated by the LLM except the questions.
"""
import hashlib

from fastapi import APIRouter
from pydantic import BaseModel

from services import gemini_service, wolfram_service

router = APIRouter()
_CACHE = {}

PICK_PROMPT = """From this documentary narration, write up to 2 short questions that Wolfram|Alpha can compute exactly and that give a viewer useful context. Good kinds:
- a historical amount of money converted to today's US dollars (include the year and currency)
- the distance between two named places
- the moon phase, sunrise or sunset on a named date at a named place
- the age of a named person on a named date
- a speed, size or temperature converted to familiar units
Only use facts stated in the narration. Each label is under 8 words and reads well on screen.
Return ONLY JSON: {"facts": [{"label": "...", "query": "..."}]}. If nothing fits, return {"facts": []}.

NARRATION:
"""


class FactsRequest(BaseModel):
    text: str


@router.post("/facts")
def facts(body: FactsRequest):
    text = (body.text or "").strip()
    if not text or not wolfram_service.is_configured():
        return {"facts": [], "provider": "Wolfram|Alpha"}
    key = hashlib.sha1(text.encode()).hexdigest()
    if key in _CACHE:
        return _CACHE[key]
    try:
        picked = (gemini_service.generate_json(PICK_PROMPT + text) or {}).get("facts") or []
    except Exception as e:
        print(f"[facts] picking failed: {str(e)[:150]}")
        picked = []
    out = []
    for f in picked[:2]:
        q, label = (f.get("query") or "").strip(), (f.get("label") or "").strip()
        answer = wolfram_service.query(q) if q else None
        if answer:
            out.append({"label": label or q, "query": q, "answer": answer})
    result = {"facts": out, "provider": "Wolfram|Alpha"}
    _CACHE[key] = result
    return result
